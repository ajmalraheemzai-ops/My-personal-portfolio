-- 2) Run this SQL.
-- 3) In Authentication > Users, create your admin user (your own email/password).
-- 4) Replace YOUR_ADMIN_USER_UUID below with that user's UUID from Auth > Users.
-- 5) Run the final policy statement after replacement.

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name varchar(120) not null,
  email varchar(254) not null,
  message text not null check (char_length(message) between 1 and 10000),
  created_at timestamptz not null default now(),
  is_read boolean not null default false
);

alter table public.contact_messages enable row level security;

-- Public visitors can submit messages only. They cannot read or edit them.
create policy "Anyone can submit contact messages"
on public.contact_messages for insert to anon, authenticated
with check (
  char_length(trim(name)) > 0 and
  char_length(trim(email)) > 0 and
  char_length(trim(message)) > 0
);

-- Admin can view, update, and delete messages. Replace UUID before running:
create policy "Admin can read messages"
on public.contact_messages for select to authenticated
using (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid);

create policy "Admin can update messages"
on public.contact_messages for update to authenticated
using (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid)
with check (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid);

create policy "Admin can delete messages"
on public.contact_messages for delete to authenticated
using (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid);
